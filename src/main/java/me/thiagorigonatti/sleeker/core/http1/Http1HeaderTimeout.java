package me.thiagorigonatti.sleeker.core.http1;

import io.netty.channel.ChannelHandlerContext;
import io.netty.handler.codec.http.HttpVersion;
import io.netty.util.concurrent.ScheduledFuture;

import java.util.concurrent.TimeUnit;

public final class Http1HeaderTimeout {

    private final long timeout;
    private final TimeUnit timeUnit;

    private ScheduledFuture<?> timeoutFuture;
    private boolean readingRequest;

    public Http1HeaderTimeout(final long timeout, final TimeUnit timeUnit) {

        if (timeout <= 0) {
            throw new IllegalArgumentException("HTTP/1 header timeout must be greater than zero");
        }

        this.timeout = timeout;
        this.timeUnit = timeUnit;
    }

    void bytesReceived(final ChannelHandlerContext ctx) {

        // If we are already receiving a body, these bytes do not belong in the header of a new request.
        if (this.readingRequest) {
            return;
        }


        // Absolute Deadline: New bytes do NOT reset the clock.
        if (this.timeoutFuture != null) {
            return;
        }

        this.timeoutFuture = ctx.executor().schedule(() -> timeout(ctx), this.timeout, this.timeUnit);
    }

    void headerCompleted() {

        cancelTimeout();

        // The HttpRequest has already been generated by the codec. Now HttpContent/LastHttpContent can be received.
        this.readingRequest = true;
    }

    void requestCompleted() {
        this.readingRequest = false;
    }

    void close() {
        cancelTimeout();
    }

    private void cancelTimeout() {

        final ScheduledFuture<?> timeoutFuture = this.timeoutFuture;

        if (timeoutFuture == null) {
            return;
        }

        this.timeoutFuture = null;

        timeoutFuture.cancel(false);
    }

    private void timeout(final ChannelHandlerContext ctx) {

        this.timeoutFuture = null;

        if (!ctx.channel().isActive()) {
            return;
        }

        Http1TimeoutResponder.timeout(ctx, HttpVersion.HTTP_1_1);
    }
}